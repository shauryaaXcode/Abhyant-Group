  const isSold = [2, 5, 8, 12, 17, 23, 29, 31, 36, 44, 49].includes(plotNum);
  const status = isSold ? 'sold' : isReserved ? 'reserved' : 'available';

  const facingList = ['East Facing', 'North Facing', 'North-East (Ishan)', 'West Facing', 'South Facing'];
  const facing = facingList[plotNum % facingList.length];

  let areaSqFt = 1000;
  let dimensionText = "25' × 40'";
  if (plotNum % 3 === 0) {
    areaSqFt = 1250;
    dimensionText = "31.25' × 40'";
  } else if (plotNum % 5 === 0) {
    areaSqFt = 1500;
    dimensionText = "30' × 50'";
  } else if (plotNum % 7 === 0) {
    areaSqFt = 2000;
    dimensionText = "40' × 50'";
  }

  const basePricePerSqFt = isCorner ? 999 : 899;
  const totalPrice = areaSqFt * basePricePerSqFt;
  const formattedPrice = `₹${(totalPrice / 100000).toFixed(2)} Lakhs`;

